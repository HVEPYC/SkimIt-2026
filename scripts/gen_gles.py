#!/usr/bin/env python3
"""Generates runner/src/hle/gles_forward.inc: HLE wrappers that forward libunity's gl* imports
(runner/imports.txt) to the device's real GLES 2.0 (Android build).

Each import is resolved against the NDK's GLES2/gl2.h. An `...OES` import whose core ES 2.0
function exists forwards to the core one. Imports with pointer semantics that need more than
address translation are in MANUAL (written by hand in gles_android.cpp). ES 1.x-only imports
(Unity runs with gles_mode 2) become logged no-ops.
"""
import glob
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANUAL = {"glGetString", "glVertexAttribPointer", "glDrawElements", "glShaderSource", "glGetVertexAttribPointerv",
          "glBindBuffer", "glDeleteBuffers", "glMapBufferOES", "glUnmapBufferOES", "glBufferData", "glBufferSubData"}
FLOAT = {"GLfloat", "GLclampf"}
INTPTR = {"GLsizeiptr", "GLintptr"}


def main():
    hdr = glob.glob(str(ROOT / "tools/android-sdk/ndk/*/toolchains/llvm/prebuilt/linux-x86_64/sysroot/usr/include/GLES2/gl2.h"))[0]
    protos = {}
    for m in re.finditer(r"GL_APICALL (.+?)\s*GL_APIENTRY (gl\w+) \((.*?)\);", Path(hdr).read_text()):
        protos[m.group(2)] = (m.group(1).strip(), m.group(3).strip())
    imports = [l.split()[0] for l in (ROOT / "runner/imports.txt").read_text().splitlines() if l.startswith("gl")]
    out = ["// Generated by scripts/gen_gles.py from runner/imports.txt and the NDK's GLES2/gl2.h. Do not edit.", ""]
    regs, noops = [], []
    for name in imports:
        if name in MANUAL:
            continue
        target = name if name in protos else (name[:-3] if name.endswith("OES") and name[:-3] in protos else None)
        if not target:
            noops.append(name)
            continue
        ret, params = protos[target]
        args, names = [], []
        if params != "void":
            for i, p in enumerate(params.split(",")):
                p = p.strip()
                typ = p[: p.rfind(re.findall(r"\w+$", p)[0])].strip()
                v = f"a{i}"
                if "*" in typ:
                    args.append(f"    auto {v} = reinterpret_cast<{typ}>(host_ptr(c.u32()));")
                elif typ in FLOAT:
                    args.append(f"    {typ} {v} = c.f32();")
                elif typ in INTPTR:
                    args.append(f"    {typ} {v} = static_cast<std::int32_t>(c.u32());")
                else:
                    args.append(f"    {typ} {v} = static_cast<{typ}>(c.u32());")
                names.append(v)
        call = f"::{target}({', '.join(names)})"
        if "*" in ret:
            raise SystemExit(f"{name}: pointer return needs a manual wrapper")
        body = f"    {call};" if ret == "void" else f"    c.ret(static_cast<std::uint32_t>({call}));"
        out += [f"void fwd_{name}(Ctx& c) {{", *args, body, "}"]
        regs.append(f'    def("{name}", fwd_{name});')
    out += ["", "void register_forwarded() {", *regs]
    out += [f'    def("{n}", gl_es1_noop);  // ES 1.x only' for n in noops]
    out += ["}", ""]
    (ROOT / "runner/src/hle/gles_forward.inc").write_text("\n".join(out))
    print(f"{len(regs)} forwarded, {len(noops)} ES1 no-ops, {len(MANUAL)} manual")


if __name__ == "__main__":
    main()
