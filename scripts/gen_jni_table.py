#!/usr/bin/env python3
"""Generates runner/src/jni/jni_table.inc (JNIEnv and JavaVM function-table order) from the NDK's jni.h."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def fields(src, struct):
    body = src[src.index("struct " + struct + " {"):]
    body = body[:body.index("};")]
    return [m.group(2) or "" for m in re.finditer(r"(void\*\s+reserved\d)|\(\*(\w+)\)", body)]


def main():
    jni_h = next(ROOT.glob("tools/android-sdk/ndk/*/toolchains/llvm/prebuilt/*/sysroot/usr/include/jni.h"), None)
    if not jni_h:
        sys.exit("jni.h not found; run scripts/bootstrap.sh")
    src = jni_h.read_text()
    out = ["// Generated by scripts/gen_jni_table.py from the NDK's jni.h. Slot order of the JNI tables.",
           "// JNI_ENV_SLOT(index, name) / JNI_VM_SLOT(index, name); reserved slots are omitted."]
    for i, n in enumerate(fields(src, "JNINativeInterface")):
        if n:
            out.append(f"JNI_ENV_SLOT({i}, {n})")
    for i, n in enumerate(fields(src, "JNIInvokeInterface")):
        if n:
            out.append(f"JNI_VM_SLOT({i}, {n})")
    (ROOT / "runner/src/jni/jni_table.inc").write_text("\n".join(out) + "\n")
    print(f"wrote {len(out) - 2} slots")


if __name__ == "__main__":
    main()
