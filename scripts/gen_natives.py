#!/usr/bin/env python3
"""Generates runner/src/jni/natives.inc: host JNI trampolines for every distinct signature of the
original app's `native` methods (work/apktool/smali; our offline WWW stand-in keeps the
original WWW signatures).

On Android, when the guest's RegisterNatives registers (class, name, sig, guest fn), the host
bridge picks a free slot of that signature's trampoline and registers it with the real JNIEnv.
Each trampoline marshals its Java arguments to the guest ABI (NativeCall in host.cpp).
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SLOTS = 8
JT = {"Z": "jboolean", "B": "jbyte", "C": "jchar", "S": "jshort", "I": "jint", "J": "jlong", "F": "jfloat", "D": "jdouble", "V": "void", "L": "jobject"}
PUT = {"Z": "i", "B": "i", "C": "i", "S": "i", "I": "i", "J": "j", "F": "f", "D": "d", "L": "l"}


def parse(sig):
    args, i = [], 1
    while sig[i] != ")":
        j = i
        while sig[j] == "[":
            j += 1
        if sig[j] == "L":
            j = sig.index(";", j)
        args.append("L" if sig[i] in "L[" else sig[i])
        i = j + 1
    r = sig[i + 1]
    return args, ("L" if r in "L[" else r)


def main():
    sigs = set()
    for f in (ROOT / "work/apktool/smali").rglob("*.smali"):
        for m in re.finditer(r"^\.method .*\bnative \S+?(\(.*)$", f.read_text(errors="replace"), re.M):
            sigs.add(m.group(1).strip())
    out = ["// Generated by scripts/gen_natives.py from the original app's native declarations. Do not edit.",
           f"// {len(sigs)} signatures x {SLOTS} slots.", ""]
    table = []
    for k, sig in enumerate(sorted(sigs)):
        args, r = parse(sig)
        params = "".join(f", {JT[a]} a{i}" for i, a in enumerate(args))
        puts = " ".join(f"c.{PUT[a]}(a{i});" for i, a in enumerate(args))
        ret = "c.call();" if r == "V" else f"return c.ret_{PUT[r]}<{JT[r]}>();"
        out.append(f"template<int S> {JT[r]} JNICALL n{k}(JNIEnv* env, jobject self{params}) {{ NativeCall c(env, self, {k}, S); {puts} {ret} }}")
        table.append(f'    {{"{sig}", {{' + ", ".join(f"(void*)&n{k}<{s}>" for s in range(SLOTS)) + "}},")
    out += ["", f"constexpr int kNativeSlots = {SLOTS};",
            "struct NativeSig { const char* sig; void* fn[kNativeSlots]; };",
            "const NativeSig kNativeSigs[] = {", *table, "};", ""]
    (ROOT / "runner/src/jni/natives.inc").write_text("\n".join(out))
    print(f"{len(sigs)} signatures")


if __name__ == "__main__":
    main()
